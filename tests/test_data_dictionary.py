"""Tests for the mart_person_year data dictionary (issue #22)."""

import copy
import re

import pytest

from health_pricing import data_dictionary as dd

DECISIONS = dd.REPO / "_docs" / "decisions.md"


@pytest.fixture(scope="module")
def model():
    return dd.load_model()


def test_the_model_has_the_37_documented_columns(model):
    assert len(model["columns"]) == 37


def test_every_column_has_a_description_and_the_three_meta_keys(model):
    assert dd.problems(model) == []


def test_the_check_fails_when_a_description_is_missing(model):
    broken = copy.deepcopy(model)
    del broken["columns"][5]["description"]
    assert dd.problems(broken) == [f"{broken['columns'][5]['name']}: no description"]


@pytest.mark.parametrize("key", dd.META_KEYS)
def test_the_check_fails_when_a_meta_key_is_missing_or_empty(model, key):
    missing = copy.deepcopy(model)
    del missing["columns"][3]["meta"][key]
    empty = copy.deepcopy(model)
    empty["columns"][3]["meta"][key] = "  "
    name = model["columns"][3]["name"]
    assert dd.problems(missing) == [f"{name}: no meta.{key}"]
    assert dd.problems(empty) == [f"{name}: no meta.{key}"]


def test_every_decision_reference_is_none_or_a_real_decisions_heading(model):
    headings = set(re.findall(r"^## (.+)$", DECISIONS.read_text(encoding="utf-8"), re.MULTILINE))
    for column in model["columns"]:
        for ref in column["meta"]["decision_ref"].split(" · "):
            assert ref == "none" or ref in headings, (column["name"], ref)


def test_the_role_meta_is_still_there(model):
    assert all(column["meta"].get("role") for column in model["columns"])


def test_the_committed_file_is_what_the_generator_produces():
    committed = dd.OUTPUT.read_text(encoding="utf-8")
    assert committed == dd.render(), "run: uv run python -m health_pricing.data_dictionary"


def test_the_file_says_it_is_generated_and_has_one_row_per_column(model):
    text = dd.render(model)
    assert "Generated by" in text.splitlines()[0]
    assert "Do not edit by hand" in text.splitlines()[0]
    rows = [line for line in text.splitlines() if line.startswith("| `")]
    assert [r.split("`")[1] for r in rows] == [c["name"] for c in model["columns"]]


def test_a_pipe_in_a_description_does_not_split_the_cell(model):
    rows = [line for line in dd.render(model).splitlines() if line.startswith("| `split`")]
    unescaped = re.split(r"(?<!\\)\|", rows[0])
    assert len(unescaped) == 7  # an empty piece at each end, and five cells

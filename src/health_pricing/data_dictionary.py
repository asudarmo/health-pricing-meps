"""Generates _docs/data-dictionary.md from the marts schema.yml entry for mart_person_year (#22).

Run `uv run python -m health_pricing.data_dictionary` after changing the descriptions or meta.
tests/test_data_dictionary.py fails if the committed file differs from what this produces.
"""

from __future__ import annotations

from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[2]
SCHEMA = REPO / "dbt" / "models" / "marts" / "schema.yml"
OUTPUT = REPO / "_docs" / "data-dictionary.md"
MODEL = "mart_person_year"
META_KEYS = ("source_vars", "derivation", "decision_ref")

HEADER = """\
<!-- Generated by `uv run python -m health_pricing.data_dictionary`. Do not edit by hand. -->

# Data dictionary: mart_person_year

This file is generated from `dbt/models/marts/schema.yml`. Do not edit it by hand. Change the
descriptions and meta in `schema.yml` and run the generator again. A test fails if the two differ.

Each row is one column of `mart_person_year`, the modelling table (one row per person-year for 2022
and 2023). Source: AHRQ, Medical Expenditure Panel Survey (MEPS), Household Component.

"""


def load_model(schema: Path = SCHEMA) -> dict:
    models = yaml.safe_load(schema.read_text(encoding="utf-8"))["models"]
    return next(m for m in models if m["name"] == MODEL)


def problems(model: dict) -> list[str]:
    """Columns that lack a description or any of the three meta keys, or have one that is empty."""
    found = []
    for column in model["columns"]:
        name = column["name"]
        if not str(column.get("description") or "").strip():
            found.append(f"{name}: no description")
        meta = column.get("meta") or {}
        for key in META_KEYS:
            if not str(meta.get(key) or "").strip():
                found.append(f"{name}: no meta.{key}")
    return found


def _cell(value: object) -> str:
    """One table cell on one line, with pipes escaped so they do not split the cell."""
    text = " ".join(str(value).split())
    return text.replace("|", "\\|")


def render(model: dict | None = None) -> str:
    return HEADER + render_table(model)


def render_table(model: dict | None = None) -> str:
    """The dictionary table alone, for the EDA notebook."""
    model = model or load_model()
    lines = [
        "| Name | Description | Source variables | Derivation | Decision reference |",
        "|---|---|---|---|---|",
    ]
    for column in model["columns"]:
        meta = column.get("meta", {})
        cells = [
            f"`{column['name']}`",
            _cell(column.get("description", "")),
            _cell(meta.get("source_vars", "")),
            _cell(meta.get("derivation", "")),
            _cell(meta.get("decision_ref", "")),
        ]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def main() -> None:
    OUTPUT.write_text(render(), encoding="utf-8", newline="\n")
    print(f"written {OUTPUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
